create or replace function reserve_meeting_booking(
  p_title text,
  p_attendee_name text,
  p_attendee_email text,
  p_notes text,
  p_start_at timestamptz,
  p_end_at timestamptz,
  p_timezone text,
  p_buffer_minutes integer
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  booking_id bigint;
begin
  if p_end_at <= p_start_at then
    raise exception 'Meeting end time must be after its start time';
  end if;
  if p_buffer_minutes < 0 then
    raise exception 'Meeting buffer cannot be negative';
  end if;

  perform pg_advisory_xact_lock(hashtext('meeting-booking'), 0);
  if exists (
    select 1 from public.meeting_bookings
    where status in ('pending', 'confirmed')
      and start_at < p_end_at + make_interval(mins => p_buffer_minutes)
      and end_at > p_start_at - make_interval(mins => p_buffer_minutes)
  ) then
    raise exception 'That time was just booked. Refresh and choose another slot'
      using errcode = '23P01';
  end if;

  insert into public.meeting_bookings(
    title, attendee_name, attendee_email, notes, start_at, end_at, timezone, status
  ) values (
    p_title, p_attendee_name, p_attendee_email, coalesce(p_notes, ''),
    p_start_at, p_end_at, p_timezone, 'pending'
  ) returning id into booking_id;
  return booking_id;
end;
$$;

create or replace function reserve_meeting_reschedule(
  p_booking_id bigint,
  p_start_at timestamptz,
  p_end_at timestamptz,
  p_buffer_minutes integer
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  existing_booking public.meeting_bookings%rowtype;
begin
  if p_end_at <= p_start_at then
    raise exception 'Meeting end time must be after its start time';
  end if;
  if p_buffer_minutes < 0 then
    raise exception 'Meeting buffer cannot be negative';
  end if;

  perform pg_advisory_xact_lock(hashtext('meeting-booking'), 0);
  select * into existing_booking
  from public.meeting_bookings
  where id = p_booking_id and status = 'confirmed'
  for update;
  if not found then
    raise exception 'Meeting was not found or is no longer active';
  end if;
  if exists (
    select 1 from public.meeting_bookings
    where id <> p_booking_id and status in ('pending', 'confirmed')
      and start_at < p_end_at + make_interval(mins => p_buffer_minutes)
      and end_at > p_start_at - make_interval(mins => p_buffer_minutes)
  ) then
    raise exception 'That time was just booked. Refresh and choose another slot'
      using errcode = '23P01';
  end if;

  update public.meeting_bookings
  set start_at = p_start_at, end_at = p_end_at, status = 'pending', updated_at = now()
  where id = p_booking_id;
  return jsonb_build_object('start_at', existing_booking.start_at, 'end_at', existing_booking.end_at);
end;
$$;

create or replace function consume_meeting_booking_rate_limit(
  p_ip_hash text,
  p_limit integer default 5,
  p_window_minutes integer default 60
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  recent_attempts integer;
begin
  if p_limit < 1 or p_window_minutes < 1 then
    raise exception 'Rate-limit settings must be positive';
  end if;
  perform pg_advisory_xact_lock(hashtext(p_ip_hash), 1);
  delete from public.meeting_booking_rate_limits
  where created_at < now() - make_interval(mins => p_window_minutes);
  select count(*) into recent_attempts
  from public.meeting_booking_rate_limits
  where ip_hash = p_ip_hash and created_at >= now() - make_interval(mins => p_window_minutes);
  if recent_attempts >= p_limit then return false; end if;
  insert into public.meeting_booking_rate_limits(ip_hash) values (p_ip_hash);
  return true;
end;
$$;

