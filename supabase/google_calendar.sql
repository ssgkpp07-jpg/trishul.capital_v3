create table if not exists google_calendar_integrations (
  id text primary key check (id = 'primary'),
  connected_email text not null,
  refresh_token_encrypted text not null,
  scopes text[] not null default '{}',
  connected_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists google_calendar_oauth_states (
  state_hash text primary key,
  admin_subject text not null,
  code_verifier text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists meeting_bookings (
  id bigint generated by default as identity primary key,
  google_event_id text unique,
  title text not null,
  attendee_name text not null,
  attendee_email text not null,
  notes text not null default '',
  start_at timestamptz not null,
  end_at timestamptz not null,
  timezone text not null,
  meet_url text not null default '',
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'cancelled', 'failed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_at > start_at)
);

create index if not exists meeting_bookings_active_time_idx
  on meeting_bookings(start_at, end_at)
  where status in ('pending', 'confirmed');

create table if not exists meeting_booking_rate_limits (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  created_at timestamptz not null default now()
);

create index if not exists meeting_booking_rate_limits_ip_created_idx
  on meeting_booking_rate_limits(ip_hash, created_at desc);
create index if not exists meeting_booking_rate_limits_created_idx
  on meeting_booking_rate_limits(created_at);

alter table google_calendar_integrations enable row level security;
alter table google_calendar_oauth_states enable row level security;
alter table meeting_bookings enable row level security;
alter table meeting_booking_rate_limits enable row level security;

revoke all on google_calendar_integrations from anon, authenticated;
