create table if not exists accounts (
  id bigint generated by default as identity primary key,
  kind text not null default 'client',
  name text not null,
  package_name text default '',
  myfxbook_url text not null default '',
  account_number text default '',
  broker_name text default '',
  investor_password text default '',
  server text default '',
  starting_capital numeric,
  online boolean not null default true,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  last_sync timestamptz
);

alter table accounts add column if not exists investor_password text default '';
alter table accounts add column if not exists server text default '';

create table if not exists snapshots (
  id bigint generated by default as identity primary key,
  account_id bigint references accounts(id) on delete cascade,
  captured_at timestamptz not null default now(),
  gain numeric,
  daily numeric,
  monthly numeric,
  yearly numeric,
  drawdown numeric,
  balance numeric,
  equity numeric,
  profit numeric,
  pips numeric,
  trades numeric,
  win_rate numeric,
  profit_factor numeric
);

create table if not exists socials (
  id bigint generated by default as identity primary key,
  platform text not null,
  url text default '',
  active boolean not null default true
);

create table if not exists settings (
  key text primary key,
  value text default ''
);

create table if not exists pages (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  title text,
  body text,
  active boolean not null default true
);

create table if not exists portfolio_clients (
  client_id text primary key,
  first_name text not null,
  second_name text not null,
  email text not null default '',
  whatsapp_number text not null default '',
  national_id text not null,
  address_line1 text not null,
  address_line2 text not null default '',
  city text not null,
  state text not null,
  country text not null,
  pincode text not null,
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);

alter table portfolio_clients add column if not exists email text not null default '';
alter table portfolio_clients add column if not exists whatsapp_number text not null default '';

create table if not exists portfolio_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('onboarded', 'funds_added', 'offboarded', 'profit_withdrawn')),
  client_id text references portfolio_clients(client_id) on delete cascade,
  client_name text not null,
  account_number text not null,
  amount numeric(14,2) not null check (amount > 0),
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);

alter table portfolio_events add column if not exists deleted_at timestamptz;
alter table portfolio_events add column if not exists client_id text references portfolio_clients(client_id) on delete cascade;

create index if not exists portfolio_events_account_created_idx on portfolio_events(account_number, created_at desc);
alter table portfolio_events drop constraint if exists portfolio_events_event_type_check;
alter table portfolio_events add constraint portfolio_events_event_type_check check (event_type in ('onboarded', 'funds_added', 'offboarded', 'profit_withdrawn'));

